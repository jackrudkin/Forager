B36 = '0123456789abcdefghijklmnopqrstuvwxyz'
def b36(n, width=3):
    n = max(0, min(36 ** width - 1, int(n)))
    s = ''
    for _ in range(width):
        s = B36[n % 36] + s
        n //= 36
    return s
def enc_xy(x, y):
    return b36(round(x * 100)) + b36(round(y * 100))

def spawns_by_map(sp):
    out = collections.defaultdict(list)
    if not isinstance(sp, dict):
        return out
    for area, coords in sp.items():
        m = area2map.get(int(area))
        if not m or m not in ZONES:
            continue
        lst = coords.values() if isinstance(coords, dict) else coords
        for c in lst:
            if isinstance(c, dict):
                x, y = c.get('1'), c.get('2')
            else:
                x, y = c[0], c[1]
            if x is None or y is None or x < 0 or y < 0 or x > 100 or y > 100:
                continue
            out[m].append((x, y))
    return out

