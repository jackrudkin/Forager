# ---------------------------------------------------------------- loot math
# Result of a template: probability that each item appears (>=1), expected count per item,
# and probability of >=1 gear item of each quality (2,3,4) plus green item level weight.
def is_gear(it):
    i = items.get(it)
    return i is not None and i['cls'] in (2, 4) and i['inv'] != 0

_cache = {}
def evaluate(table, entry, depth=0):
    key = (table, entry)
    if key in _cache:
        return _cache[key]
    units = []  # list of (item_probs dict, quality_probs dict, expected dict, greenIlvlWeight)
    groups = collections.defaultdict(list)
    for (it, ch, g, mc, mx) in loot[table].get(entry, []):
        if ch < 0:  # quest-only item
            continue
        if g and g > 0:
            groups[g].append((it, ch, mc, mx))
        else:
            p = (ch if ch > 0 else 100.0) / 100.0
            units.append(single(it, p, mc, mx, depth))
    for g, ents in groups.items():
        explicit = sum(ch for (_, ch, _, _) in ents if ch > 0)
        equal = [e for e in ents if e[1] == 0]
        share_eq = max(0.0, 100.0 - explicit) / len(equal) if equal else 0.0
        ip, qp, ex, gw = {}, {2: 0.0, 3: 0.0, 4: 0.0}, {}, [0.0, 0.0]
        for (it, ch, mc, mx) in ents:
            share = (ch if ch > 0 else share_eq) / 100.0
            if share <= 0:
                continue
            u = single(it, share, mc, mx, depth)
            for k, v in u[0].items(): ip[k] = ip.get(k, 0.0) + v
            for k, v in u[1].items(): qp[k] = min(1.0, qp[k] + v)
            for k, v in u[2].items(): ex[k] = ex.get(k, 0.0) + v
            gw[0] += u[3][0]; gw[1] += u[3][1]
        units.append((ip, qp, ex, gw))
    ip, ex = {}, {}
    notq = {2: 1.0, 3: 1.0, 4: 1.0}
    gw = [0.0, 0.0]
    notitem = {}
    for (uip, uqp, uex, ugw) in units:
        for k, v in uip.items(): notitem[k] = notitem.get(k, 1.0) * (1.0 - min(1.0, v))
        for k, v in uqp.items(): notq[k] *= (1.0 - min(1.0, v))
        for k, v in uex.items(): ex[k] = ex.get(k, 0.0) + v
        gw[0] += ugw[0]; gw[1] += ugw[1]
    ip = {k: 1.0 - v for k, v in notitem.items()}
    res = (ip, {k: 1.0 - v for k, v in notq.items()}, ex, gw)
    _cache[key] = res
    return res

def single(it, p, mc, mx, depth):
    if mc is not None and mc < 0:  # reference
        if depth > 6:
            return ({}, {2: 0, 3: 0, 4: 0}, {}, [0, 0])
        reps = max(1, mx or 1)
        ip, qp, ex, gw = evaluate('reference_loot_template', -mc, depth + 1)
        rip = {k: 1.0 - (1.0 - p * v) ** reps for k, v in ip.items()}
        rqp = {k: 1.0 - (1.0 - p * v) ** reps for k, v in qp.items()}
        rex = {k: v * p * reps for k, v in ex.items()}
        return (rip, rqp, rex, [gw[0] * p * reps, gw[1] * p * reps])
    avg = ((mc or 1) + (mx or mc or 1)) / 2.0
    qp = {2: 0.0, 3: 0.0, 4: 0.0}
    gw = [0.0, 0.0]
    if is_gear(it):
        q = items[it]['q']
        if q in qp:
            qp[q] = p
        if q == 2:
            gw = [p * items[it]['ilvl'], p]
    return ({it: p}, qp, {it: p * avg}, gw)

